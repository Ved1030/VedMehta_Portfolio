import { readdirSync, writeFileSync } from 'node:fs';
import { join, extname } from 'node:path';

const IMAGES_DIR = join(import.meta.dirname, '..', 'public', 'images');
const OUTPUT_FILE = join(import.meta.dirname, '..', 'src', 'data', 'image-manifest.ts');

const IMAGE_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg']);

// Map folder names (normalized) → project title
const FOLDER_TO_PROJECT = {
  trustwealth: 'TrustWealth AI',
  zipdrop: 'ZipDrop',
  aura: 'AURA',
  'skill lab': 'SkillLab',
  pravaas: 'Prvaas',
  constituency: 'Constituency Dev Platform',
  petclinic: 'Pet Clinic',
  'noble classes': 'Noble Classes',
  chronocancer: 'ChronoCancer AI',
  glam: 'GlamSpot',
  'achievements mind2flow': 'Achievements',
};

function normalizeFolder(name) {
  return name.toLowerCase().replace(/[\s_-]+/g, ' ').trim();
}

function scanImages(dir) {
  try {
    const entries = readdirSync(dir, { withFileTypes: true });
    return entries
      .filter((e) => e.isFile() && IMAGE_EXTENSIONS.has(extname(e.name).toLowerCase()))
      .map((e) => e.name)
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));
  } catch {
    return [];
  }
}

function generateManifest() {
  const manifest = {};
  let totalImages = 0;

  const folders = readdirSync(IMAGES_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name);

  for (const folder of folders) {
    const files = scanImages(join(IMAGES_DIR, folder));
    const key = normalizeFolder(folder);
    const projectTitle = FOLDER_TO_PROJECT[key] || folder;

    const paths = files.map((f) => `/images/${folder}/${f}`);

    manifest[projectTitle] = {
      folder: `/images/${folder}`,
      count: paths.length,
      thumbnail: paths[0] || null,
      images: paths,
    };

    totalImages += paths.length;

    if (paths.length > 0) {
      console.log(`✓ Loaded ${projectTitle} (${paths.length} images) — /images/${folder}/`);
    } else {
      console.log(`⚠ ${projectTitle} — /images/${folder}/ (empty)`);
    }
  }

  console.log(`\nTotal: ${totalImages} images across ${folders.length} folders\n`);

  // Generate TypeScript
  const lines = [
    '// AUTO-GENERATED by scripts/generate-image-manifest.mjs',
    '// Do not edit manually. Run: npm run images',
    '',
    'export interface ProjectImages {',
    '  folder: string;',
    '  count: number;',
    '  thumbnail: string | null;',
    '  images: string[];',
    '}',
    '',
    'export const projectImages: Record<string, ProjectImages> = {',
  ];

  for (const [title, data] of Object.entries(manifest)) {
    const escaped = title.replace(/'/g, "\\'");
    lines.push(`  '${escaped}': {`);
    lines.push(`    folder: '${data.folder}',`);
    lines.push(`    count: ${data.count},`);
    lines.push(`    thumbnail: ${data.thumbnail ? `'${data.thumbnail}'` : 'null'},`);
    lines.push(`    images: [`);
    for (const img of data.images) {
      lines.push(`      '${img}',`);
    }
    lines.push(`    ],`);
    lines.push(`  },`);
  }

  lines.push('};');
  lines.push('');

  writeFileSync(OUTPUT_FILE, lines.join('\n'), 'utf-8');
  console.log(`Manifest written to ${OUTPUT_FILE}`);
}

generateManifest();
